#!/usr/bin/env bash
# Writes generated/envoy.yaml: deploy/envoy/envoy.yaml plus a cluster for the mock
# provider, over plain HTTP. Nothing else changes, so the integration run uses the shipped
# bootstrap; the node controller is told to route decrypted requests to that cluster
# (--decrypt-cluster), and the listeners are the ones it serves.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p generated
{
  echo "# GENERATED by test/integration/make-envoy-config.sh. Do not edit."
  cat ../../deploy/envoy/envoy.yaml
  cat <<'YAML'

  - name: mock_anthropic
    type: STRICT_DNS
    connect_timeout: 1s
    # The mock's s4-a-trailers response ends in an HTTP/1.1 trailer; Envoy drops those
    # unless asked, and the SDK run checks the processor's trailers path with it.
    typed_extension_protocol_options:
      envoy.extensions.upstreams.http.v3.HttpProtocolOptions:
        "@type": type.googleapis.com/envoy.extensions.upstreams.http.v3.HttpProtocolOptions
        explicit_http_config: { http_protocol_options: { enable_trailers: true } }
    load_assignment:
      cluster_name: mock_anthropic
      endpoints: [{ lb_endpoints: [{ endpoint: { address: { socket_address: { address: mock-anthropic, port_value: 8080 } } } }] }]
YAML
} > generated/envoy.yaml
echo "wrote $(pwd)/generated/envoy.yaml"
