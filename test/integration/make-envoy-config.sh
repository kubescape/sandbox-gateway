#!/usr/bin/env bash
# Writes generated/envoy.yaml: deploy/envoy/envoy.yaml with the AI hosts' route pointed at a
# cluster for the mock provider, over plain HTTP. Nothing else changes, so the
# integration run exercises the shipped listener, TLS and ext_proc config.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p generated
python3 - <<'PY'
s = open('../../deploy/envoy/envoy.yaml').read()
old = "                route: { cluster: dfp, timeout: 0s, idle_timeout: 300s }"
new = "                route: { cluster: mock_anthropic, timeout: 0s, idle_timeout: 300s }"
assert s.count(old) == 1, "route anchor not found exactly once in envoy.yaml"
s = s.replace(old, new).rstrip() + """

  - name: mock_anthropic
    type: STRICT_DNS
    connect_timeout: 1s
    # The mock's s4-a-trailers response ends in an HTTP/1.1 trailer; Envoy drops those
    # unless asked, and the SDK run checks the processor's trailers path with it.
    typed_extension_protocol_options:
      envoy.extensions.upstreams.http.v3.HttpProtocolOptions:
        "@type": type.googleapis.com/envoy.extensions.upstreams.http.v3.HttpProtocolOptions
        explicit_http_config: { http_protocol_options: { enable_trailers: true } }
    load_assignment:
      cluster_name: mock_anthropic
      endpoints: [{ lb_endpoints: [{ endpoint: { address: { socket_address: { address: mock-anthropic, port_value: 8080 } } } }] }]
"""
open('generated/envoy.yaml', 'w').write("# GENERATED by test/integration/make-envoy-config.sh. Do not edit.\n" + s)
PY
echo "wrote $(pwd)/generated/envoy.yaml"
